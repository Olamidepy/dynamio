/**
 * Deterministically generates today's Daily Challenge level based on the date string (YYYY-MM-DD)
 */
export function getDailyChallengeLevel(dateString: string): LevelConfig {
  let hash = 0;
  for (let i = 0; i < dateString.length; i++) {
    hash = (hash << 5) - hash + dateString.charCodeAt(i);
    hash |= 0;
  }
  const absHash = Math.abs(hash);
  const baseLevelIdx = absHash % LEVELS.length;
  const baseLevel = LEVELS[baseLevelIdx];

  return {
    ...baseLevel,
    id: 1000,
    name: `Daily Trial: ${dateString}`,
    description: `Official Nimiq Daily Arcade Challenge for ${dateString}. Compete on the daily leaderboard!`,
    totalBalls: Math.floor(45 + (absHash % 25)),
    speed: 3.3 + ((absHash % 15) / 10),
    colorPool: ['ruby', 'sapphire', 'amber', 'emerald', 'amethyst'],
    difficulty: 'HARD',
    targetScore: 10000 + (absHash % 5000),
    baseRewardNim: 2.5,
    baseRewardEnergy: 500,
  };
}
